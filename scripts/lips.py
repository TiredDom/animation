"""Mouth tracks for every voice line: how open (from the loudness) and how round (from the letters being said),
one value per film frame. Writes assets/film/lips.js, which the shots read to move the mouths.

    python scripts/lips.py
"""
import json
import subprocess
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
FPS = 30
SR = 16000
ROUND = set('oOuUwW')
WIDE = set('eEiIyY')


def pcm(path):
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', str(path), '-ac', '1', '-ar', str(SR), '-f', 's16le', '-'],
                         capture_output=True, check=True).stdout
    return np.frombuffer(raw, np.int16).astype(np.float32) / 32768.0


def track(lid):
    y = pcm(ROOT / f'assets/vo/{lid}.mp3')
    hop = SR // FPS
    n = int(np.ceil(len(y) / hop))
    rms = np.array([np.sqrt(np.mean(y[i * hop:(i + 1) * hop] ** 2) + 1e-12) for i in range(n)])
    db = 20 * np.log10(rms)
    top = np.percentile(db, 95)
    # open from about 30 dB under the line's loud parts, full at its loud parts; eased so small sounds still move
    o = np.clip((db - (top - 30)) / 30, 0, 1) ** 1.3
    # never hold a mouth open across a pause: a short smooth, then gaps close
    o = np.convolve(o, [0.25, 0.5, 0.25], mode='same')
    al = json.loads((ROOT / f'assets/vo/{lid}.json').read_text(encoding='utf-8'))['alignment']
    rnd = np.zeros(n)
    wide = np.zeros(n)
    for ch, a, b in zip(al['characters'], al['character_start_times_seconds'], al['character_end_times_seconds']):
        i0, i1 = int(a * FPS), max(int(a * FPS) + 1, int(b * FPS))
        if ch in ROUND:
            rnd[i0:i1] = 1
        elif ch in WIDE:
            wide[i0:i1] = 1
    rnd = np.convolve(rnd, [0.2, 0.6, 0.2], mode='same')
    wide = np.convolve(wide, [0.2, 0.6, 0.2], mode='same')
    return [round(float(v), 3) for v in o], [round(float(v), 2) for v in rnd], [round(float(v), 2) for v in wide]


def main():
    lines = json.loads((ROOT / 'assets/vo/lines.json').read_text(encoding='utf-8'))
    out = {}
    for x in lines:
        o, r, w = track(x['id'])
        out[x['id']] = {'open': o, 'round': r, 'wide': w}
    path = ROOT / 'assets/film/lips.js'
    path.write_text('// Generated by scripts/lips.py: per voice line, per film frame, mouth open / round / wide (0..1).\n'
                    'export const LIPS = ' + json.dumps(out, separators=(',', ':')) + ';\n', encoding='utf-8')
    print(f'{len(out)} lines -> {path.relative_to(ROOT)} ({path.stat().st_size // 1024} KB)')


if __name__ == '__main__':
    main()
